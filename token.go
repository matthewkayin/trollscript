type TokenKind int
const (
	// One-char tokens
	TOKEN_LEFT_PAREN  TokenKind = iota
	TOKEN_RIGHT_PAREN
	TOKEN_LEFT_BRACE
	TOKEN_RIGHT_BRACE
	TOKEN_PLUS
	TOKEN_MINUS
	TOKEN_SLASH
	TOKEN_STAR
	TOKEN_COMMA
	TOKEN_DOT
	TOKEN_BANG

	// Two-char tokens
	TOKEN_EQUAL
	TOKEN_EQUAL_EQUAL
	TOKEN_BANG_EQUAL
	TOKEN_GREATER
	TOKEN_GREATER_EQUAL
	TOKEN_LESS
	TOKEN_LESS_EQUAL

	// Literals
	TOKEN_NUMBER
	TOKEN_STRING
	TOKEN_IDENTIFIER

	// Keywords
	TOKEN_IF
	TOKEN_ELSE
	TOKEN_ELSE_IF
	TOKEN_LET
	TOKEN_AND
	TOKEN_OR
	TOKEN_RETURN
	TOKEN_FUNC
	TOKEN_NIL
	TOKEN_TRUE
	TOKEN_FALSE

	// Other
	TOKEN_EOF
)

type Token struct {
	kind TokenKind
	lexeme string
	line int
	literal any
}
